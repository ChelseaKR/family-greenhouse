// Time
// ---------------------------------------------------------------------------

/**
 * `date` plus `months` calendar months, in UTC, with the day clamped to the
 * target month's length: 31 January + 1 month is 28 (or 29) February, never
 * 3 March. `Date.UTC` alone would roll the overflow forward and hand a
 * one-month gift redeemed on the 31st a few extra days — or, on 29–31 March
 * minus a month, the wrong month entirely. The time of day is kept, so the
 * gift ends at the same instant of the day it started.
 */
export function addCalendarMonthsUtc(date: Date, months: number): Date {
  const y = date.getUTCFullYear();
  const m = date.getUTCMonth();
  const d = date.getUTCDate();
  const targetMonthStart = new Date(Date.UTC(y, m + months, 1));
  const daysInTarget = new Date(
    Date.UTC(targetMonthStart.getUTCFullYear(), targetMonthStart.getUTCMonth() + 1, 0)
  ).getUTCDate();
  return new Date(
    Date.UTC(
      targetMonthStart.getUTCFullYear(),
      targetMonthStart.getUTCMonth(),
      Math.min(d, daysInTarget),
      date.getUTCHours(),
      date.getUTCMinutes(),
      date.getUTCSeconds(),
      date.getUTCMilliseconds()
    )
  );
}

// ---------------------------------------------------------------------------
// The Stripe event → grant projection
// ---------------------------------------------------------------------------

/** True when a Checkout Session was minted by `createGiftCheckoutSession`. */
export function isGiftSession(session: { metadata?: Record<string, string> | null }): boolean {
  return session.metadata?.purchase === GIFT_SUBSCRIPTION_PURCHASE_KIND;
}

export interface GiftPurchaseGrant {
  /** Stripe Checkout Session id — the idempotency key of the grant. */
  stripeSessionId: string;
  planId: GiftablePlanId;
  months: number;
  /** The account that paid. The code is shown to this account and nobody else. */
  buyerUserId: string;
  /** ISO timestamp the payment completed; the redeem-by window counts from here. */
  purchasedAt: string;
}

/**
 * The gift a Stripe event describes, or null for anything else.
 *
 * Only a PAID gift checkout grants. `checkout.session.completed` arrives with
 * `payment_status: 'unpaid'` for deferred payment methods; the later
 * `checkout.session.async_payment_succeeded` carries the same session and
 * grants then. Everything the grant needs is read from the metadata stamped
 * at checkout, so the webhook grants what was sold at the time, and a paid
 * session whose metadata is missing or nonsensical returns null — which
 * `applyStripeEvent` turns into the alarmed `stripe_event_paid_no_grant`,
 * never into an invented gift.
 */
export function giftPurchaseFromEvent(event: Stripe.Event): GiftPurchaseGrant | null {
  if (
    event.type !== 'checkout.session.completed' &&
    event.type !== 'checkout.session.async_payment_succeeded'
  ) {
    return null;
  }
  const session = event.data.object as unknown as {
    id?: string;
    mode?: string;
    payment_status?: string;
    metadata?: Record<string, string> | null;
  };
  if (!isGiftSession(session)) return null;
  if (session.mode !== 'payment' || session.payment_status !== 'paid') return null;
  if (typeof session.id !== 'string' || session.id === '') return null;
  const planId = session.metadata?.giftPlanId;
  if (!isGiftablePlanId(planId)) return null;
  const months = Number(session.metadata?.months);
  if (!isValidGiftMonths(months)) return null;
  const buyerUserId = session.metadata?.buyerUserId ?? '';
  if (!buyerUserId) return null;
  return {
    stripeSessionId: session.id,
    planId,
    months,
    buyerUserId,
    purchasedAt: new Date(event.created * 1000).toISOString(),
  };
}
