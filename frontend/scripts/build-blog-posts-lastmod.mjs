#!/usr/bin/env node
/**
 * Keep each blog post's `updated` date honest, in
 * `frontend/scripts/blog-posts-lastmod.json`.
 *
 * ## Why a ledger
 *
 * A post's `<lastmod>`, `dateModified` and `article:modified_time` all come
 * from one hand-typed field, `updated` in `src/features/blog/posts/index.ts`.
 * Nothing made anyone type it: until 2026-11-17 the field did not exist and
 * all 14 posts published their publish date as their modified date, some of
 * them five months and two retitles later.
 *
 * So the ledger records, per post, a digest of what the post says (its
 * source file, and its title and descriptions in the manifest) beside the
 * date the manifest gives it. `blog-posts-lastmod.test.mjs`, which
 * `npm run test:edge` and so `npm run verify` run, fails when a post's digest
 * no longer matches the ledger, or its date does. The way to make it pass is
 * this script, and this script refuses to record a changed post under an
 * unchanged date. An edit therefore cannot ship without either a new
 * `updated` or the explicit statement below that readers see no difference.
 *
 * Usage:
 *   node scripts/build-blog-posts-lastmod.mjs
 *   node scripts/build-blog-posts-lastmod.mjs --same-words <slug> [<slug>…]
 *
 * `--same-words` re-records the named posts under their current date. It is
 * for a change no reader or crawler can see, such as a renamed import.
 * Whitespace is already ignored, so reformatting needs nothing.
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const POSTS_DIR = join(HERE, '..', 'src', 'features', 'blog', 'posts');

/** The committed ledger, beside this script. */
export const BLOG_LEDGER = join(HERE, 'blog-posts-lastmod.json');

const COMMENT =
  'Generated by `npm run blog:lastmod --workspace frontend`; do not edit by hand. Each ' +
  '/blog/<slug> post’s `content` is a digest of its source file and its title and descriptions ' +
  'in posts/index.ts, recorded beside the date the manifest gives it (`updated`, else `date`). ' +
  'See frontend/scripts/build-blog-posts-lastmod.mjs.';

const squash = (text) => text.replace(/\s+/g, ' ').trim();

/**
 * Every post in the manifest source, as `{ slug, lastmod, date, words, file }`.
 *
 * `words` is the entry with its two dates and reading time taken out, so
 * changing `updated` alone does not read as a change of content. `file` is
 * the post's module, resolved through the manifest's own import of its
 * `Component`.
 */
export function manifestPosts(source) {
  const imports = new Map(
    [...source.matchAll(/import (\w+) from '\.\/([\w-]+)';/g)].map((m) => [m[1], m[2]])
  );
  const starts = [...source.matchAll(/\bslug:\s*'([^']+)'/g)];
  return starts.map((m, i) => {
    const entry = source.slice(m.index, starts[i + 1]?.index ?? source.length);
    const date = /\bdate:\s*'([^']+)'/.exec(entry)?.[1];
    const updated = /\bupdated:\s*'([^']+)'/.exec(entry)?.[1];
    const component = /\bComponent:\s*(\w+)/.exec(entry)?.[1];
    const end = /\bComponent:\s*\w+/.exec(entry);
    const words = squash(
      entry
        .slice(0, end ? end.index : entry.length)
        .replace(/\b(date|updated):\s*'[^']*',?/g, '')
        .replace(/\breadingMinutes:\s*\d+,?/g, '')
    );
    return {
      slug: m[1],
      date,
      lastmod: updated ?? date,
      words,
      file: component && imports.get(component),
    };
  });
}

/** Digest of what one post says: its manifest words and its source file. */
export function postContentDigest(post, fileSource) {
  return createHash('sha256')
    .update(post.words)
    .update('\n')
    .update(squash(fileSource))
    .digest('hex')
    .slice(0, 16);
}

/** The manifest's posts with their current digests, read from disk. */
export function currentPosts(postsDir = POSTS_DIR) {
  const source = readFileSync(join(postsDir, 'index.ts'), 'utf8');
  return manifestPosts(source).map((post) => {
    if (!post.file) throw new Error(`No Component import found for the post "${post.slug}".`);
    const fileSource = readFileSync(join(postsDir, `${post.file}.tsx`), 'utf8');
    return { ...post, content: postContentDigest(post, fileSource) };
  });
}

export function readBlogLedger(path = BLOG_LEDGER) {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch {
    return { posts: {} };
  }
}

const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

/**
 * What is wrong between the manifest and the ledger, one line per problem.
 * Empty means every post's date is the one recorded for the words it has now.
 */
export function ledgerFailures(posts, ledger) {
  const failures = [];
  const recorded = ledger?.posts ?? {};
  for (const post of posts) {
    if (!post.date || !ISO_DATE.test(post.date) || !ISO_DATE.test(post.lastmod)) {
      failures.push(`${post.slug}: \`date\` and \`updated\` must be ISO dates (YYYY-MM-DD).`);
      continue;
    }
    if (post.lastmod < post.date) {
      failures.push(
        `${post.slug}: \`updated\` (${post.lastmod}) is before \`date\` (${post.date}).`
      );
    }
    const prior = recorded[post.slug];
    if (!prior) {
      failures.push(
        `${post.slug}: not in the ledger. Run \`npm run blog:lastmod --workspace frontend\`.`
      );
    } else if (prior.content !== post.content) {
      failures.push(
        `${post.slug}: the post has changed since ${prior.lastmod}, the date recorded for it. ` +
          'Set `updated` in posts/index.ts to the day this ships, then run ' +
          '`npm run blog:lastmod --workspace frontend`.'
      );
    } else if (prior.lastmod !== post.lastmod) {
      failures.push(
        `${post.slug}: the manifest says ${post.lastmod} and the ledger says ${prior.lastmod}. ` +
          'Run `npm run blog:lastmod --workspace frontend`.'
      );
    }
  }
  const live = new Set(posts.map((post) => post.slug));
  for (const slug of Object.keys(recorded)) {
    if (!live.has(slug)) {
      failures.push(
        `${slug}: in the ledger but not in posts/index.ts. Run \`npm run blog:lastmod --workspace frontend\`.`
      );
    }
  }
  return failures;
}

/**
 * The next ledger, or the posts it refuses to record. A post whose words
 * changed while its date did not is refused unless it is named in
 * `sameWords`. Pure, so the refusal is testable without the file system.
 */
export function nextLedger(previous, posts, sameWords = new Set()) {
  const next = {};
  const refused = [];
  for (const post of posts) {
    const prior = previous?.posts?.[post.slug];
    const changedUnderOldDate =
      prior && prior.content !== post.content && prior.lastmod === post.lastmod;
    if (changedUnderOldDate && !sameWords.has(post.slug)) refused.push(post.slug);
    next[post.slug] = { content: post.content, lastmod: post.lastmod };
  }
  return { ledger: { $comment: COMMENT, posts: next }, refused };
}

function main() {
  const args = process.argv.slice(2);
  const flag = args.indexOf('--same-words');
  const sameWords = new Set(flag === -1 ? [] : args.slice(flag + 1));
  const { ledger, refused } = nextLedger(readBlogLedger(), currentPosts(), sameWords);
  if (refused.length > 0) {
    console.error(
      'These posts changed but still carry the date recorded for their old text:\n' +
        refused.map((slug) => `  - ${slug}`).join('\n') +
        '\n\nSet `updated` in src/features/blog/posts/index.ts to the day the change ships and ' +
        'run this again.\nIf readers and crawlers see no difference, run it with ' +
        '`--same-words <slug>` instead.'
    );
    process.exit(1);
  }
  writeFileSync(BLOG_LEDGER, `${JSON.stringify(ledger, null, 2)}\n`);
  console.log(`blog posts lastmod: ${Object.keys(ledger.posts).length} posts recorded.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
