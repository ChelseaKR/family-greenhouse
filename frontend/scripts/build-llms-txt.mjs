#!/usr/bin/env node
/**
 * Build `public/llms.txt` (llmstxt.org) from the same data the pages render.
 *
 * ## What is hand-kept and what is generated
 *
 * `scripts/llms-header.txt` is the hand-kept part: the H1, the summary, the
 * pricing, pet-safety and citation paragraphs, and the `## Pages` list. It is
 * copied through byte for byte. Everything after it is generated:
 *
 *   - `## Care guides`: one line per guide in `careGuides.ts`, in manifest
 *     order. The link text is the guide's own H1; the note is its scientific
 *     name and the Water and Light lines of its "At a glance" box.
 *   - `## Pet safety pages`: one line per published `/pet-safe/<slug>` page.
 *     The link text is the page's H1; the note is the scientific name and the
 *     verdict word the page shows for cats and for dogs, then the source.
 *
 * The file used to name the two families and stop ("one guide per plant under
 * /care/<plant>"), so an assistant reading it learned that 120 pages existed
 * and not which plants they covered. A hand-kept list would have gone stale
 * with the next batch of guides, which is why this one is derived.
 *
 * ## What a pet-safety line may say
 *
 * Exactly what the page says and nothing more. The verdict for each animal is
 * `claimFor()`'s, the rule the page and its build gate share: `toxic` or
 * `non-toxic` only when the table records it AND the plant's own ASPCA listing
 * states the same; otherwise "Not assessed". The words are the catalog's
 * verdict labels, never "safe", and every line names the ASPCA as the source.
 * A plant with no published page gets no line.
 *
 * ## The "Last updated" date
 *
 * `scripts/llms-txt-lastmod.json` records a digest of the file's text (the
 * date line left out) and the date that digest was first seen. The date moves
 * when, and only when, the text does: a rebuild on a later day with the same
 * guides and the same header writes the same date. It is the same rule the
 * plant pages' sitemap `<lastmod>` follows (`build-plant-pages-lastmod.mjs`),
 * for the same reason: a date that moves with every build tells a reader
 * nothing, and teaches it to ignore the date.
 *
 * Usage:
 *   node scripts/build-llms-txt.mjs           # write llms.txt and the ledger
 *   node scripts/build-llms-txt.mjs --check   # fail if either is out of date
 *
 * `scripts/llms-txt.test.mjs` (`npm run test:edge`, a step of `npm run
 * verify`) runs the same comparison, so a stale committed file fails the gate.
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';
import process from 'node:process';
import { runInNewContext } from 'node:vm';

import { faqName, publishedPlantPages } from './pet-toxicity-table.mjs';
import { FRONTEND_ROOT, SITE } from './public-routes.mjs';

const require = createRequire(import.meta.url);

export const LLMS_TXT = join(FRONTEND_ROOT, 'public', 'llms.txt');
export const LLMS_HEADER = join(FRONTEND_ROOT, 'scripts', 'llms-header.txt');
export const LLMS_LEDGER = join(FRONTEND_ROOT, 'scripts', 'llms-txt-lastmod.json');
const CARE_GUIDES = join(FRONTEND_ROOT, 'src', 'features', 'care', 'careGuides.ts');
const EN_CATALOG = join(FRONTEND_ROOT, 'src', 'i18n', 'locales', 'en', 'translation.json');

/** The header's last section. The date line goes directly above it. */
const PAGES_HEADING = '## Pages';

const LEDGER_COMMENT =
  'Generated by `npm run llms --workspace frontend`; do not edit by hand. `lastmod` is the date ' +
  'the `content` digest (llms.txt without its "Last updated" line) was first seen. See ' +
  'frontend/scripts/build-llms-txt.mjs.';

const text = (value) => typeof value === 'string' && value.trim().length > 0;

/**
 * Transpile and evaluate `careGuides.ts`, the way `loadPetToxicityTable()`
 * evaluates the pet table. THROWS on zero guides: sixty-four guides parsed as
 * none means this loader broke, and the silent version of that is an
 * llms.txt that stops listing every guide.
 */
export function loadCareGuides(source = readFileSync(CARE_GUIDES, 'utf8')) {
  const ts = require('typescript');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
    fileName: 'careGuides.ts',
  });
  if (/\brequire\(/.test(outputText)) {
    throw new Error(
      `${CARE_GUIDES} now imports another module. build-llms-txt.mjs evaluates it in ` +
        'isolation; keep the manifest dependency-free, or teach loadCareGuides() to resolve it.'
    );
  }
  const module = { exports: {} };
  runInNewContext(outputText, { module, exports: module.exports }, { filename: CARE_GUIDES });
  const guides = module.exports.CARE_GUIDES;
  if (!Array.isArray(guides) || guides.length === 0) {
    throw new Error(`${CARE_GUIDES} evaluated to no CARE_GUIDES entries.`);
  }
  return guides;
}

/** The two catalog strings a pet-safety line is composed from, plus the three verdict words. */
export function readPetSafetyWords(path = EN_CATALOG) {
  const page = JSON.parse(readFileSync(path, 'utf8')).plantSafetyPage;
  const words = {
    heading: page?.heading,
    toxic: page?.verdict?.toxic,
    'non-toxic': page?.verdict?.nonToxic,
    'not-assessed': page?.verdict?.notAssessed,
  };
  for (const [key, value] of Object.entries(words)) {
    if (!text(value)) throw new Error(`${path} has no plantSafetyPage string for "${key}".`);
  }
  return words;
}

/** One sentence: the value with any closing period removed, then exactly one. */
const sentence = (value) => `${value.trim().replace(/\.+$/, '')}.`;

/**
 * A guide's line. THROWS on a guide missing any field the line shows: a line
 * that reads "Water: undefined." is the defect this repository names, and a
 * guide silently left out is the same defect one step removed.
 */
export function careGuideLine(guide) {
  const need = {
    slug: guide?.slug,
    commonName: guide?.commonName,
    scientificName: guide?.scientificName,
    'quickFacts.water': guide?.quickFacts?.water,
    'quickFacts.light': guide?.quickFacts?.light,
  };
  for (const [field, value] of Object.entries(need)) {
    if (!text(value)) {
      throw new Error(
        `care guide "${guide?.slug ?? '?'}" has no ${field}; llms.txt cannot list it.`
      );
    }
  }
  // careGuideHeading() in careGuides.ts: the page's visible H1.
  const heading = text(guide.heading) ? guide.heading : `${guide.commonName} care`;
  return (
    `- [${heading}](${SITE}/care/${guide.slug}): ${sentence(guide.scientificName)} ` +
    `Water: ${sentence(guide.quickFacts.water)} Light: ${sentence(guide.quickFacts.light)}`
  );
}

/** A published plant page's line. `page` is one of `publishedPlantPages()`. */
export function petSafetyLine(page, words) {
  const { entry, claims } = page;
  if (!text(entry?.commonName) || !text(entry?.scientificName)) {
    throw new Error(`pet-safety page "${page?.slug ?? '?'}" has no name; llms.txt cannot list it.`);
  }
  const word = (animal) => {
    const label = words[claims?.[animal]?.state];
    if (!text(label)) {
      throw new Error(`pet-safety page "${page.slug}" has no verdict state for ${animal}.`);
    }
    return label;
  };
  const heading = words.heading.replace('{{questionName}}', faqName(entry.commonName));
  return (
    `- [${heading}](${SITE}${page.path}): ${sentence(entry.scientificName)} ` +
    `Cats: ${word('cats')}. Dogs: ${word('dogs')}. Source: ASPCA plant list.`
  );
}

/** llms.txt without its date line: the header, then the two generated lists. */
export function llmsBody({
  header = readFileSync(LLMS_HEADER, 'utf8'),
  guides = loadCareGuides(),
  pages = publishedPlantPages(),
  words = readPetSafetyWords(),
} = {}) {
  if (!header.includes(`\n${PAGES_HEADING}\n`)) {
    throw new Error(`${LLMS_HEADER} has no "${PAGES_HEADING}" section.`);
  }
  if (pages.length === 0) throw new Error('no published pet-safety pages; llms.txt lists none.');
  return [
    header.trimEnd(),
    '',
    '## Care guides',
    '',
    ...guides.map(careGuideLine),
    '',
    '## Pet safety pages',
    '',
    ...pages.map((page) => petSafetyLine(page, words)),
    '',
  ].join('\n');
}

export function contentDigest(body) {
  return `sha256-${createHash('sha256').update(body).digest('hex')}`;
}

export const dateLine = (lastmod) => `Last updated: ${lastmod}.`;

/**
 * The body with its date line, directly above `## Pages`. llmstxt.org allows
 * paragraphs only before the first H2, so that is where it has to go.
 */
export function withDate(body, lastmod) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(lastmod))) {
    throw new Error(`llms.txt has no date to print: "${lastmod}" is not YYYY-MM-DD.`);
  }
  const at = body.indexOf(`\n${PAGES_HEADING}\n`);
  if (at === -1) throw new Error(`llms.txt body has no "${PAGES_HEADING}" section.`);
  return `${body.slice(0, at)}\n${dateLine(lastmod)}\n${body.slice(at)}`;
}

/**
 * The next ledger. Pure, so "the date moves only when the text does" is
 * testable without a clock: `today` is written only for a digest not yet seen.
 */
export function nextLedger(previous, digest, today) {
  const kept = previous?.content === digest && /^\d{4}-\d{2}-\d{2}$/.test(previous?.lastmod);
  return { $comment: LEDGER_COMMENT, content: digest, lastmod: kept ? previous.lastmod : today };
}

export function readLedger(path = LLMS_LEDGER) {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') return {};
    throw error;
  }
}

/**
 * What the committed file must be, or the reason it cannot be said. It never
 * falls back to today: a ledger that does not match the text has no date for
 * it, and `--check` (and the test) report that instead of printing one.
 */
export function expectedLlmsTxt({ body = llmsBody(), ledger = readLedger() } = {}) {
  const digest = contentDigest(body);
  if (ledger?.content !== digest) {
    return {
      error:
        'frontend/scripts/llms-txt-lastmod.json does not match what llms.txt would say now. ' +
        'Run `npm run llms --workspace frontend` and commit llms.txt and the ledger.',
    };
  }
  return { text: withDate(body, ledger.lastmod) };
}

function main() {
  const check = process.argv.includes('--check');
  const body = llmsBody();

  if (check) {
    const expected = expectedLlmsTxt({ body });
    if (expected.error) {
      console.error(`llms:check: ${expected.error}`);
      process.exit(1);
    }
    if (readFileSync(LLMS_TXT, 'utf8') !== expected.text) {
      console.error(
        'llms:check: frontend/public/llms.txt is not what the generator writes. ' +
          'Run `npm run llms --workspace frontend` and commit the result.'
      );
      process.exit(1);
    }
    console.log('llms:check: public/llms.txt matches the header, the guides and the pet table.');
    return;
  }

  const previous = readLedger();
  const ledger = nextLedger(previous, contentDigest(body), new Date().toISOString().slice(0, 10));
  writeFileSync(LLMS_LEDGER, `${JSON.stringify(ledger, null, 2)}\n`);
  writeFileSync(LLMS_TXT, withDate(body, ledger.lastmod));
  const lines = body.split('\n').filter((line) => line.startsWith('- [')).length;
  console.log(
    `llms: wrote public/llms.txt (${lines} links), last updated ${ledger.lastmod}` +
      (previous.content === ledger.content ? ' (text unchanged, date kept).' : ' (text changed).')
  );
}

const invokedDirectly = process.argv[1] && import.meta.url === `file://${process.argv[1]}`;
if (invokedDirectly) main();
