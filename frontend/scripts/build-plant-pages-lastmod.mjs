#!/usr/bin/env node
/**
 * Re-date the `/pet-safe/<slug>` pages whose content changed, in
 * `frontend/scripts/plant-pages-lastmod.json`.
 *
 * ## Why a ledger
 *
 * A sitemap `<lastmod>` is a claim about the page: "this is when what you will
 * read here last changed" (#722 is the reference fix, for /changelog). Care
 * guides and blog posts carry that date in their manifests. The pet-toxicity
 * table carries none, and inventing one per entry would be a hand-typed date
 * nobody can check. Using the build date would be worse: every deploy would
 * tell crawlers every plant page changed.
 *
 * So the ledger records, per page, a digest of every table field the page
 * shows and the date that digest was first seen. `public-routes.mjs` gives a
 * page its ledger date only while the digest still matches; the moment the
 * table entry changes, the route loses its date and `build-sitemap.mjs`
 * refuses to build or check until this script is run. This script is the only
 * thing that moves a date, and it moves only the dates of pages whose digest
 * changed — a page whose content is unchanged keeps its date no matter what
 * day this runs.
 *
 * It writes and exits; there is no `--check` mode, because the check is the
 * sitemap's (`npm run sitemap:check`, a step of `npm run verify`).
 *
 * Usage:  node scripts/build-plant-pages-lastmod.mjs
 */

import { writeFileSync } from 'node:fs';
import process from 'node:process';

import { LASTMOD_LEDGER, pageContentDigest, publishedPlantPages } from './pet-toxicity-table.mjs';
import { readPlantPagesLedger } from './public-routes.mjs';

const COMMENT =
  'Generated by `npm run plant-pages:lastmod --workspace frontend`; do not edit by hand. ' +
  'Each /pet-safe/<slug> page’s sitemap <lastmod> is the date its `content` digest (every ' +
  'table field the page shows) was first seen. See frontend/scripts/build-plant-pages-lastmod.mjs.';

/**
 * The next ledger. Pure, so the "a date moves only when content does" property
 * is testable without a clock: `today` is only ever written for a page whose
 * digest is new or different.
 */
export function nextLedger(previous, pages, today) {
  const next = {};
  for (const page of pages) {
    const content = pageContentDigest(page.entry);
    const prior = previous?.pages?.[page.slug];
    next[page.slug] =
      prior && prior.content === content
        ? { content, lastmod: prior.lastmod }
        : { content, lastmod: today };
  }
  return { $comment: COMMENT, pages: next };
}

function main() {
  const previous = readPlantPagesLedger();
  const today = new Date().toISOString().slice(0, 10);
  const ledger = nextLedger(previous, publishedPlantPages(), today);

  const before = previous.pages ?? {};
  const changed = Object.keys(ledger.pages).filter(
    (slug) => before[slug]?.content !== ledger.pages[slug].content
  );
  const removed = Object.keys(before).filter((slug) => !(slug in ledger.pages));

  writeFileSync(LASTMOD_LEDGER, `${JSON.stringify(ledger, null, 2)}\n`);
  console.log(
    `plant-pages:lastmod: ${Object.keys(ledger.pages).length} pages; ` +
      `${changed.length} re-dated to ${today}${changed.length ? ` (${changed.join(', ')})` : ''}; ` +
      `${removed.length} removed${removed.length ? ` (${removed.join(', ')})` : ''}.`
  );
}

const invokedDirectly = process.argv[1] && import.meta.url === `file://${process.argv[1]}`;
if (invokedDirectly) main();
