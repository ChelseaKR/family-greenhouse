import { resolve } from 'path';
import { runnerImport, type Plugin } from 'vite';

/** The module the browser build replaces. See its header for the contract. */
export const CARE_GUIDE_SOURCE = resolve(__dirname, 'src/features/care/careGuideSource.ts');

/**
 * What this plugin reads from careGuideSource.ts. Typed here rather than with
 * `typeof import(...)`, which would pull src/ into the tsconfig.node project.
 */
interface CareGuideSourceModule {
  CARE_GUIDE_INDEX: readonly unknown[];
}

/**
 * The browser build's stand-in for careGuideSource.ts: the index as a literal,
 * and no guides. Exported so the test suite can check it against the module
 * it replaces.
 */
export function careGuideClientModule(index: CareGuideSourceModule['CARE_GUIDE_INDEX']): string {
  return [
    '// Generated by vite.careGuideContent.ts from src/features/care/careGuideSource.ts.',
    `export const CARE_GUIDE_INDEX = JSON.parse(${JSON.stringify(JSON.stringify(index))});`,
    'export function bundledCareGuide() { return undefined; }',
    '',
  ].join('\n');
}

/**
 * Keep the care-guide prose out of the browser's JavaScript.
 *
 * careGuides.ts is ~230 kB of prose. Imported by the /care, /care/:slug and
 * /pet-safe pages, it was emitted as one 53 kB (brotli) chunk, and the
 * All-JS-combined budget counts every emitted chunk, so each new guide spent
 * that budget whether or not anyone downloaded it. The pages need the full
 * text of one guide at a time, and only the prerendered guide page has it.
 *
 * So, in the browser build only, careGuideSource.ts is loaded here (with
 * Vite's module runner, in Node) and replaced by careGuideClientModule's
 * output. Nothing in the bundle then imports careGuides.ts for its data. The
 * dev server, the tests and the SSR prerender build are untouched and keep
 * reading the module itself, so the prerendered HTML is rendered from exactly
 * the data it was before; scripts/prerender.mjs additionally writes each
 * guide's JSON into its own page for the browser to hydrate from.
 */
export function careGuideContent(): Plugin {
  let browserBuild = false;

  return {
    name: 'family-greenhouse:care-guide-content',
    apply: 'build',
    configResolved(config) {
      browserBuild = !config.build.ssr;
    },
    async load(id) {
      if (!browserBuild || id.split('?')[0] !== CARE_GUIDE_SOURCE) return null;
      const { module } = await runnerImport<CareGuideSourceModule>(CARE_GUIDE_SOURCE, {
        configFile: false,
        logLevel: 'silent',
      });
      return careGuideClientModule(module.CARE_GUIDE_INDEX);
    },
  };
}
